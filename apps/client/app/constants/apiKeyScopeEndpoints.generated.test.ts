// @vitest-environment node
import { readFileSync } from 'node:fs';
import path from 'node:path';
import * as prettier from 'prettier';
import { describe, expect, it, vi } from 'vitest';
import { ApiKeyScope } from '@bike4mind/common';
import {
  HELPERS,
  VERBS,
  deriveScopeEndpoints,
  gatesIn,
  pageRouteFiles,
  routePathOf,
  servesVerb,
  stripComments,
} from '../../scripts/apiKeyScopeRoutes';
import { NON_MINTABLE_API_KEY_SCOPES } from '@bike4mind/server-utils/app/constants/apiKeyScopes';

// Only the gate lists are needed; keep dataLakeScopes from loading the services graph.
vi.mock('@bike4mind/services', () => ({}));
vi.mock('@server/auth/turnAuth', () => ({}));

const GENERATED_FILE = path.resolve(
  __dirname,
  '../../../../packages/server-utils/src/app/constants/apiKeyScopeEndpoints.generated.ts'
);
const MEMBER_BY_SCOPE = new Map(Object.entries(ApiKeyScope).map(([member, value]) => [value, member]));

/** The generated module's source for `derived`, in enum order, scopes that open nothing left out. */
function renderGeneratedModule(derived: ReadonlyMap<ApiKeyScope, readonly string[]>): string {
  const entries = Object.values(ApiKeyScope)
    .filter(scope => (derived.get(scope)?.length ?? 0) > 0)
    .map(scope => `  [ApiKeyScope.${MEMBER_BY_SCOPE.get(scope)}]: ${JSON.stringify(derived.get(scope))},`);
  return [
    "// Generated by apps/client/app/constants/apiKeyScopeEndpoints.generated.test.ts from each route's",
    '// own scope checks (see apps/client/scripts/apiKeyScopeRoutes.ts). Do not edit by hand: after',
    "// changing a route's scopes, run `pnpm --filter @bike4mind/client gen:api-key-scope-endpoints`",
    '// and commit the result.',
    "import { ApiKeyScope } from '@bike4mind/common';",
    '',
    '/** For each scope, every core route a key holding only that scope gets through. */',
    'export const DERIVED_API_KEY_SCOPE_ENDPOINTS: Readonly<Partial<Record<ApiKeyScope, readonly string[]>>> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

describe('apiKeyScopeEndpoints.generated.ts', () => {
  it('lists every route each scope opens, as the routes declare it today', async () => {
    const scopes = Object.values(ApiKeyScope).filter(scope => !NON_MINTABLE_API_KEY_SCOPES.has(scope));
    const source = renderGeneratedModule(deriveScopeEndpoints(scopes));
    const options = await prettier.resolveConfig(GENERATED_FILE);
    const formatted = await prettier.format(source, { ...options, filepath: GENERATED_FILE });
    // Stale output fails here (CI never writes snapshots); `gen:api-key-scope-endpoints` rewrites it.
    await expect(formatted).toMatchFileSnapshot(GENERATED_FILE);
  });

  it('can see a verb on every route file that checks a scope', () => {
    // A route the generator cannot place under a verb is left out of every list without a sound,
    // which is the understatement this file exists to end. Teach servesVerb the file's idiom.
    const unread = pageRouteFiles().filter(file => {
      const source = stripComments(readFileSync(file, 'utf8'));
      return (
        routePathOf(file) !== undefined &&
        gatesIn(source, HELPERS).length > 0 &&
        !VERBS.some(verb => servesVerb(source, verb))
      );
    });
    expect(unread.map(file => path.relative(__dirname, file))).toEqual([]);
  });
});
