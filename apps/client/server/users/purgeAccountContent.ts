type PurgeOptions = { logger: Pick<Logger, 'info' | 'warn' | 'error'>; assertLease: () => Promise<void> };
const BATCH_SIZE = 100;
type PurgeRecord = {
  userId?: string | mongoose.Types.ObjectId;
  sessionId?: string;
  id?: string;
  dataLakeId?: string;
  organizationId?: string | null;
  users?: { userId?: string; sessionId?: string }[];
  sessionIds?: string[];
  adminUserIds?: string[];
  userDetails?: { id: string }[];
  listingIds?: string[];
  tags?: { name: string }[];
};

/** Raw collections deliberately include tombstones and permanently erase instead of soft-deleting. */
function collectionFor(modelName: string) {
  const database = mongoose.connection.db;
  if (!database) throw new Error('Account purge requires a connected database');
  return database.collection<PurgeRecord>(mongoose.model<Record<string, unknown>>(modelName).collection.name);
}

const ownerFilter = (userId: string) => ({ userId: { $in: [userId, new mongoose.Types.ObjectId(userId)] } });
const personalFilter = (userId: string, personalOrganizationIds: readonly string[]) => ({
  $or: [
    { ...ownerFilter(userId), organizationId: { $in: [null, ''] } },
    { organizationId: { $in: personalOrganizationIds } },
  ],
});

async function purgeNotebookMedia(
  userId: string,
  personalOrganizationIds: readonly string[],
  sessionId: string,
  assertLease: () => Promise<void>
) {
  const quests = collectionFor(Quest.modelName);
  const cursor = quests.find({ sessionId }, { projection: { images: 1, videos: 1 } });
  for await (const quest of cursor) {
    const media = z
      .object({ images: z.array(z.string()).nullish(), videos: z.array(z.string()).nullish() })
      .parse(quest);
    for (const key of new Set([...(media.images ?? []), ...(media.videos ?? [])])) {
      await assertLease();
      // Forks/clones keep their own replies but reuse the generated bytes. Any other user's
      // notebook or surviving file remains an owner of those bytes, including soft-deleted copies.
      const references = quests.find({ $or: [{ images: key }, { videos: key }] }, { projection: { sessionId: 1 } });
      let retained = false;
      for await (const reference of references) {
        if (reference.sessionId === sessionId) continue;
        if (typeof reference.sessionId !== 'string') throw new Error('Generated media reference has no session ID');
        const notebook = await collectionFor(Session.modelName).findOne({
          _id: new mongoose.Types.ObjectId(reference.sessionId),
          ...personalFilter(userId, personalOrganizationIds),
        });
        if (!notebook) {
          retained = true;
          break;
        }
      }
      if (retained || (await collectionFor(FabFile.modelName).findOne({ 'sourceMetadata.generatedCopyKey': key })))
        continue;
      await getGeneratedImageStorage().deletePermanently(key);
    }
  }
}

async function purgeNotebooks(
  userId: string,
  personalOrganizationIds: readonly string[],
  assertLease: () => Promise<void>
) {
  const sessions = collectionFor(Session.modelName);
  while (true) {
    const batch = await sessions
      .find(personalFilter(userId, personalOrganizationIds), { projection: { _id: 1 } })
      .limit(BATCH_SIZE)
      .toArray();
    if (batch.length === 0) return;
    for (const notebook of batch) {
      await assertLease();
      const sessionId = String(notebook._id);
      await purgeNotebookMedia(userId, personalOrganizationIds, sessionId, assertLease);
      // The parent survives every failure, so a retry retains the key to all dependent messages.
      await collectionFor(Quest.modelName).deleteMany({ sessionId });
      for (const model of ['SessionAgentConfig', 'SessionToolApproval']) {
        await collectionFor(model).deleteMany({ sessionId });
      }
      await collectionFor('FabFile').updateMany({ 'users.sessionId': sessionId }, { $pull: { users: { sessionId } } });
      await collectionFor('Project').updateMany({ sessionIds: sessionId }, { $pull: { sessionIds: sessionId } });
      await sessions.deleteOne({ _id: notebook._id, ...personalFilter(userId, personalOrganizationIds) });
    }
  }
}

async function purgeArtifacts(
  userId: string,
  personalOrganizationIds: readonly string[],
  assertLease: () => Promise<void>
) {
  const artifacts = collectionFor(Artifact.modelName);
  while (true) {
    const batch = await artifacts
      .find(personalFilter(userId, personalOrganizationIds), { projection: { id: 1 } })
      .limit(BATCH_SIZE)
      .toArray();
    if (batch.length === 0) return;
    for (const artifact of batch) {
      await assertLease();
      const artifactId = z.string().min(1).parse(artifact.id);
      await collectionFor(ArtifactContent.modelName).deleteMany({ artifactId });
      await collectionFor(ArtifactVersion.modelName).deleteMany({ artifactId });
      await artifacts.deleteOne({ _id: artifact._id, ...personalFilter(userId, personalOrganizationIds) });
    }
  }
}

async function purgePublishedOriginals(
  userId: string,
  personalOrganizationIds: readonly string[],
  assertLease: () => Promise<void>
) {
  const publications = collectionFor('PublishedArtifact');
  const ownedPublications = {
    $or: [{ ownerId: userId }, { tier: 'organization', scopeId: { $in: personalOrganizationIds } }],
  };
  const pathSegment = z.string().regex(/^[A-Za-z0-9_-]+$/);
  const schema = z.object({
    publicId: pathSegment,
    tier: z.enum(['user', 'project', 'organization']),
    scopeId: pathSegment,
    slug: pathSegment,
    source: z.object({ kind: z.enum(['bundle', 'reply', 'fabfile']) }),
    storageKeyPrefix: z.string().optional(),
  });
  while (true) {
    const batch = await publications.find(ownedPublications).limit(BATCH_SIZE).toArray();
    if (batch.length === 0) return;
    for (const record of batch) {
      await assertLease();
      const publication = schema.parse(record);
      const storage = getPublishedArtifactsStorage();
      if (publication.source.kind === 'bundle') {
        const prefix = buildPublishS3KeyPrefix(publication.tier, publication.scopeId, publication.slug);
        if (publication.storageKeyPrefix !== prefix)
          throw new Error('Refusing a non-canonical publication purge prefix');
        // A tombstoned slug may have been republished by somebody else under the same S3 prefix.
        if (!(await publications.findOne({ storageKeyPrefix: prefix, $nor: [ownedPublications] }))) {
          await storage.deletePrefixPermanently(prefix);
        }
      }
      await storage.deletePrefixPermanently(publishThumbnailPrefix(publication.publicId));
      for (const model of ['Annotation', 'PublishedArtifactReport', 'PublishedArtifactViewAudit']) {
        await collectionFor(model).deleteMany({ publicId: publication.publicId });
      }
      await publications.deleteOne({ _id: record._id, ...ownedPublications });
    }
  }
}

async function purgePersonalSkills(
  userId: string,
  personalOrganizationIds: readonly string[],
  assertLease: () => Promise<void>
) {
  const listings = collectionFor('SkillListing');
  const ownedListings = {
    $or: [
      { authorUserId: userId, organizationId: { $in: [null, ''] } },
      { organizationId: { $in: personalOrganizationIds } },
    ],
  };
  while (true) {
    const batch = await listings.find(ownedListings).limit(BATCH_SIZE).toArray();
    if (batch.length === 0) break;
    for (const listing of batch) {
      await assertLease();
      const listingId = String(listing._id);
      await collectionFor('SkillListingVersion').deleteMany({ listingId });
      await collectionFor('SkillListingImport').deleteMany({ listingId });
      await collectionFor('SkillListingReport').deleteMany({ listingId });
      await collectionFor('SkillBundle').updateMany({ listingIds: listingId }, { $pull: { listingIds: listingId } });
      await listings.deleteOne({ _id: listing._id, ...ownedListings });
    }
  }
  // Imported skills are independent records; only this user's personal copies go.
  await collectionFor('SkillBundle').deleteMany({ organizationId: { $in: personalOrganizationIds } });
  await collectionFor('Skill').deleteMany(personalFilter(userId, personalOrganizationIds));
  await collectionFor('SkillListingImport').deleteMany(ownerFilter(userId));
}

async function purgeDeepAgentRecords(userId: string, assertLease: () => Promise<void>) {
  const charters = collectionFor('DeepAgentCharter');
  while (true) {
    const batch = await charters.find({ 'identity.ownerUserId': userId }).limit(BATCH_SIZE).toArray();
    if (batch.length === 0) return;
    for (const charter of batch) {
      await assertLease();
      const { identity } = z.object({ identity: z.object({ agentId: z.string().min(1) }) }).parse(charter);
      await memoryPrincipalKeyRepository.destroy('agent', identity.agentId);
      await collectionFor('MemoryLedgerEvent').deleteMany({ principalKind: 'agent', principalId: identity.agentId });
      for (const model of ['DeepAgentHandoff', 'DeepAgentEpisode']) {
        await collectionFor(model).deleteMany({ agentId: identity.agentId });
      }
      await charters.deleteOne({ _id: charter._id, 'identity.ownerUserId': userId });
    }
  }
}

async function purgeQuestGraphs(userId: string, assertLease: () => Promise<void>) {
  const graphs = collectionFor('QuestGraph');
  while (true) {
    const batch = await graphs
      .find(ownerFilter(userId), { projection: { _id: 1 } })
      .limit(BATCH_SIZE)
      .toArray();
    if (batch.length === 0) return;
    for (const graph of batch) {
      await assertLease();
      await collectionFor('QuestNode').deleteMany({ graphId: String(graph._id) });
      await graphs.deleteOne({ _id: graph._id, ...ownerFilter(userId) });
    }
  }
}

async function purgePersonalLakes(
  userId: string,
  personalOrganizationIds: readonly string[],
  assertLease: () => Promise<void>
) {
  const lakes = collectionFor('DataLake');
  const grantsCollection = collectionFor('DataLakeAccessGrant');
  const grantSchema = z.object({
    principalType: z.enum(['user', 'organization']),
    principalId: z.string(),
    role: z.enum(['owner', 'curator', 'reader']),
  });
  const purgeLake = async (record: PurgeRecord & { _id: mongoose.mongo.ObjectId }) => {
    await assertLease();
    const lake = z.object({ createdByUserId: z.string(), datalakeTag: z.string().min(1) }).parse(record);
    const dataLakeId = String(record._id);
    const grants = await grantsCollection
      .find({
        dataLakeId,
        $or: [{ expiresAt: null }, { expiresAt: { $gt: new Date() } }],
      })
      .toArray();
    const owners = dataLakeService.resolveEffectiveOwnerIds(
      lake,
      grants.map(grant => grantSchema.parse(grant))
    );
    // Creator provenance cannot override a transfer. A co-owned/shared lake also has surviving
    // owners, so remove only this user's access later and leave its content and memory intact.
    if (!personalOrganizationIds.includes(record.organizationId ?? '') && (owners.length !== 1 || owners[0] !== userId))
      return;
    await memoryPrincipalKeyRepository.destroy('lake', lake.datalakeTag);
    await collectionFor('MemoryLedgerEvent').deleteMany({ principalKind: 'lake', principalId: lake.datalakeTag });
    for (const model of [
      'DataLakeBatch',
      'DataLakeResearchConfig',
      'DataLakeResearchRun',
      'DataLakeProposal',
      'DataLakeFinding',
      'DataLakeHealthSnapshot',
      'DataLakeSpendNotification',
      'DataLakeCorpusAction',
      'LakeMembershipDecision',
      'LakeMembershipRemoval',
      'LakeMembershipChangeEvent',
      'LakeConfigChangeEvent',
      'LakeSkippedFile',
      'LakeAccessEvent',
      'LakeAccessQueryText',
      'DataLakeOwnershipOffer',
    ]) {
      await assertLease();
      await collectionFor(model).deleteMany({ dataLakeId });
    }
    for (const model of ['OrgGoogleDriveConnection', 'OrgGitHubLakeConnection']) {
      await collectionFor(model).deleteMany({
        dataLakeId,
        organizationId: { $in: [null, '', ...personalOrganizationIds] },
      });
    }
    // Surviving uploads belong to other users or an organization. Only detach the removed lake's
    // unique membership tag; deleting the lake never authorizes deleting their bytes.
    await collectionFor(FabFile.modelName).updateMany(
      { 'tags.name': lake.datalakeTag },
      { $pull: { tags: { name: lake.datalakeTag } } }
    );
    // Ownership grants are the retry anchor for a transferred-in lake. Delete them only in the
    // same transaction as the lake, or a failed final write would restore the original creator
    // fallback and make this user's remaining lake unreachable to a retry.
    await withTransaction(async session => {
      await assertLease();
      await grantsCollection.deleteMany({ dataLakeId }, { session });
      await lakes.deleteOne(
        { _id: record._id, organizationId: { $in: [null, '', ...personalOrganizationIds] } },
        { session }
      );
    });
  };
  const personal = { organizationId: { $in: [null, '', ...personalOrganizationIds] } };
  for await (const lake of lakes.find({
    ...personal,
    $or: [{ createdByUserId: userId }, { organizationId: { $in: personalOrganizationIds } }],
  }))
    await purgeLake(lake);
  // A transferred-in lake has somebody else's immutable creator field.
  for await (const grant of grantsCollection.find({ principalType: 'user', principalId: userId, role: 'owner' })) {
    const id = z
      .string()
      .regex(/^[a-f0-9]{24}$/i)
      .parse(grant.dataLakeId);
    const lake = await lakes.findOne({ ...personal, _id: new mongoose.Types.ObjectId(id) });
    if (lake) await purgeLake(lake);
  }
}

async function purgePersonalProjects(
  userId: string,
  personalOrganizationIds: readonly string[],
  assertLease: () => Promise<void>
) {
  const projects = collectionFor('Project');
  while (true) {
    const batch = await projects
      .find(personalFilter(userId, personalOrganizationIds), { projection: { _id: 1 } })
      .limit(BATCH_SIZE)
      .toArray();
    if (batch.length === 0) return;
    for (const project of batch) {
      await assertLease();
      const projectId = String(project._id);
      // Members keep the grants a project minted on surviving (organization or other owners')
      // documents unless they go with it, as deleteProject's revoke cascade does.
      for (const model of [FabFile.modelName, Session.modelName]) {
        await collectionFor(model).updateMany({ 'users.projectId': projectId }, { $pull: { users: { projectId } } });
      }
      await projects.deleteOne({ _id: project._id, ...personalFilter(userId, personalOrganizationIds) });
    }
  }
}

async function purgePersonalAgents(
  userId: string,
  personalOrganizationIds: readonly string[],
  assertLease: () => Promise<void>
) {
  const agents = collectionFor('Agent');
  while (true) {
    const batch = await agents
      .find(personalFilter(userId, personalOrganizationIds), { projection: { _id: 1 } })
      .limit(BATCH_SIZE)
      .toArray();
    if (batch.length === 0) return;
    await assertLease();
    const agentIds = batch.map(agent => String(agent._id));
    // Same cleanup as deleteAgent: nobody's Slack setting may keep pointing at a removed agent.
    await collectionFor('User').updateMany(
      { 'slackSettings.customAgentId': { $in: agentIds } },
      { $unset: { 'slackSettings.customAgentId': '' } }
    );
    await agents.deleteMany({
      _id: { $in: batch.map(agent => agent._id) },
      ...personalFilter(userId, personalOrganizationIds),
    });
  }
}

async function purgePersonalUsage(
  userId: string,
  personalOrganizationIds: readonly string[],
  assertLease: () => Promise<void>
) {
  await assertLease();
  await collectionFor('CounterLog').deleteMany(ownerFilter(userId));
  const usage = collectionFor('UsageEvent');
  await usage.deleteMany({
    $or: [
      { ...ownerFilter(userId), ownerType: { $ne: 'Organization' } },
      { ownerType: 'User', ownerId: userId },
      { ownerType: 'Organization', ownerId: { $in: personalOrganizationIds } },
    ],
  });
  // Organization billing totals belong to a surviving organization. Keep quantities, prices and
  // ownership, while severing the deleted person's identifiers and links to private content.
  for await (const row of usage.find(ownerFilter(userId), { projection: { _id: 1 } })) {
    await assertLease();
    await usage.updateOne(
      { _id: row._id, ...ownerFilter(userId) },
      {
        $set: { userId: 'deleted-account', requestId: randomUUID() },
        $unset: { sessionId: '', dataLakeId: '', apiKeyId: '' },
      }
    );
  }
}

async function purgePersonalMemory(
  userId: string,
  personalOrganizationIds: readonly string[],
  assertLease: () => Promise<void>
) {
  await assertLease();
  // Keep the destruction fence: deleting the key row outright would let an in-flight append
  // recreate a live key after erasure. The tombstone holds no decryptable memory content.
  await memoryPrincipalKeyRepository.destroy('user', userId);
  await collectionFor('MemoryLedgerEvent').deleteMany({ principalKind: 'user', principalId: userId });
  const agents = collectionFor('Agent').find(personalFilter(userId, personalOrganizationIds), {
    projection: { _id: 1 },
  });
  for await (const agent of agents) {
    await assertLease();
    const principalId = String(agent._id);
    await memoryPrincipalKeyRepository.destroy('agent', principalId);
    await collectionFor('MemoryLedgerEvent').deleteMany({ principalKind: 'agent', principalId });
  }
}

/**
 * Strict, resumable removal for a claimed self-serve deletion. No catch converts a failed purge
 * into completion; the User deletion marker remains until every step resolves. Ownership predicates
 * remove the user's personal originals, while organization-owned records and other owners' copies
 * survive. Auth/security audit records follow their existing TTL and are not swept here.
 */
export async function purgeAccountContent(userId: string, { logger, assertLease }: PurgeOptions): Promise<void> {
  await assertLease();
  const workspaces = await collectionFor('Organization')
    .find({ ...ownerFilter(userId), personal: true }, { projection: { _id: 1 } })
    .toArray();
  const personalOrganizationIds = workspaces.map(workspace => String(workspace._id));
  await purgeUserPublishedArtifacts(userId, { deletedBy: userId, logger });
  await withdrawAuthorListings(userId);
  await purgePublishedOriginals(userId, personalOrganizationIds, assertLease);
  await purgePersonalSkills(userId, personalOrganizationIds, assertLease);
  await purgeNotebooks(userId, personalOrganizationIds, assertLease);
  await purgeArtifacts(userId, personalOrganizationIds, assertLease);
  await purgePersonalMemory(userId, personalOrganizationIds, assertLease);
  await purgeDeepAgentRecords(userId, assertLease);
  await purgeQuestGraphs(userId, assertLease);
  await purgePersonalLakes(userId, personalOrganizationIds, assertLease);
  await purgePersonalUsage(userId, personalOrganizationIds, assertLease);

  await purgePersonalProjects(userId, personalOrganizationIds, assertLease);
  await purgePersonalAgents(userId, personalOrganizationIds, assertLease);

  for (const model of [
    'ToolModel',
    'Memento',
    'ResearchAgent',
    'ResearchTask',
    'WorkItem',
    'AgentExecution',
    'Favorite',
    'Tag',
    'BriefcasePrompt',
    'ImageGenerationTemplate',
    'ResearchData',
    'StockPortfolio',
    'StockTrade',
    'TavernQuest',
    'QuestMasterPlan',
    'QuestExternalLink',
    'GearStamp',
  ]) {
    await assertLease();
    await collectionFor(model).deleteMany(personalFilter(userId, personalOrganizationIds));
  }

  for (const model of [
    'AuthSession',
    'TrustedDevice',
    'PasskeyCredential',
    'OAuthGrant',
    'OAuthRefreshToken',
    'OAuthAuthorizationCode',
    'UserApiKey',
    'ApiKey',
    'PushToken',
    'DeviceAuthorization',
    'CcBridgeDevice',
    'CcBridgePairingToken',
    'WsConnectTicket',
    'PasskeyChallenge',
    'UserActivityCounter',
    'UserUsagePatternSignals',
    'AdminUserNote',
    'AdminUserNoteRevision',
  ]) {
    await assertLease();
    await collectionFor(model).deleteMany(ownerFilter(userId));
  }
  for (const model of [
    'Connection',
    'ActiveCodeAgent',
    'CodeAgentEvent',
    'SessionAgentConfig',
    'SessionToolApproval',
  ]) {
    await assertLease();
    await collectionFor(model).deleteMany(ownerFilter(userId));
  }
  await collectionFor('GitHubLakeAuthGrant').deleteMany(ownerFilter(userId));
  await collectionFor('Inbox').deleteMany({ receiverId: userId });
  await collectionFor('Friendship').deleteMany({ $or: [{ requester: userId }, { recipient: userId }] });
  await collectionFor('McpConnection').deleteMany({ ownerType: 'user', ownerKey: userId });
  await collectionFor('McpServer').deleteMany(ownerFilter(userId));
  await collectionFor('GenerationJob').deleteMany({
    $or: [
      { ownerType: CreditHolderType.User, ownerId: userId },
      { ownerType: CreditHolderType.Organization, ownerId: { $in: personalOrganizationIds } },
    ],
  });
  await collectionFor('Activity').deleteMany({
    $or: [
      { ownerType: 'User', ownerId: userId },
      { ownerType: 'Organization', ownerId: { $in: personalOrganizationIds } },
    ],
  });
  await collectionFor('TaskSchedule').deleteMany({ 'payload.userId': userId });
  // A share received from another owner is an access row, never that owner's content.
  for (const model of [Session.modelName, 'Project', FabFile.modelName, 'Agent', 'ToolModel']) {
    await assertLease();
    await collectionFor(model).updateMany({ 'users.userId': userId }, { $pull: { users: { userId } } });
  }
  await assertLease();
  await collectionFor('Organization').updateMany(
    { $or: [{ 'users.userId': userId }, { adminUserIds: userId }, { 'userDetails.id': userId }] },
    { $pull: { users: { userId }, adminUserIds: userId, userDetails: { id: userId } } }
  );
  await collectionFor('DataLakeAccessGrant').deleteMany({ principalType: 'user', principalId: userId });
  await embedConversationRepository.deleteAllForUser(userId);
  await integrationRequestRepository.deleteAllForUser(userId);
  await hideDeletedAuthorAnnotations(userId);
  await retainDeletedSignupTraces(userId);
  await authEventRepository.deleteAllForUser(userId);
  await shadowDetectionRepository.removeUser(userId);
  logger.info(`[AccountDeletion] Purged personal content for user ${userId}`);
}
