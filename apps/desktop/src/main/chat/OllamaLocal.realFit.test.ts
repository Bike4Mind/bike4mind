import { afterEach, describe, expect, it, vi } from 'vitest';
import { AUTO_LOCAL_CONTEXT } from '@shared/localContextSetting';
import { unifiedMachine } from './fitStub.testHelper';
import { HardwareProbe, localContextSizing } from './localContextSizing';
import { forgetLocalContexts, OllamaLocal } from './OllamaLocal';

// OllamaLocal.test.ts stubs the estimator; these run the real one on a 16 GB Mac.
const QWEN3_8B = {
  'general.architecture': 'qwen3',
  'qwen3.attention.head_count': 32,
  'qwen3.attention.head_count_kv': 8,
  'qwen3.attention.key_length': 128,
  'qwen3.attention.value_length': 128,
  'qwen3.block_count': 36,
  'qwen3.context_length': 131072,
  'qwen3.embedding_length': 4096,
};
const BLOB = (n: number) => `/store/blobs/sha256-${String(n).repeat(64)}`;

function ollama(show: Record<string, unknown> = {}) {
  vi.stubGlobal(
    'fetch',
    vi.fn(async (input: unknown) => {
      const url = String(input);
      if (url.endsWith('/api/tags'))
        return Response.json({ models: [{ name: 'qwen3', size: 5_027_797_508, digest: 'one' }] });
      if (url.endsWith('/api/show'))
        return Response.json({ capabilities: ['completion'], model_info: QWEN3_8B, ...show });
      return new Response('', { status: 404 });
    })
  );
}

const mac16 = (projectorBytes?: (modelfile: string) => Promise<number>) =>
  localContextSizing({
    setting: async () => AUTO_LOCAL_CONTEXT,
    hardware: new HardwareProbe(async () => unifiedMachine(16)),
    projectorBytes,
  });

describe('OllamaLocal context sizing with the real fit estimate', () => {
  afterEach(() => {
    vi.unstubAllGlobals();
    forgetLocalContexts();
  });

  it('lists a model only under the Settings sizes it cannot load, layers in system RAM included', async () => {
    ollama();
    const fit = await new OllamaLocal(undefined, mac16()).contextFit();
    // 32K misses the GPU part of a 16 GB Mac but loads with layers past it.
    expect(fit[16384]).toBeUndefined();
    expect(fit[32768]).toBeUndefined();
    expect(fit[131072]).toEqual(['qwen3']);
  });

  it("sizes the projector from the Modelfile's FROM lines", async () => {
    const modelfile = `# Modelfile generated by "ollama show"\nFROM ${BLOB(1)}\nFROM ${BLOB(2)}\nTEMPLATE x\n`;
    ollama({ modelfile });
    const projectorBytes = vi.fn(async () => 0);
    await new OllamaLocal(undefined, mac16(projectorBytes)).contextFit();
    expect(projectorBytes).toHaveBeenCalledWith(modelfile);
  });
});
