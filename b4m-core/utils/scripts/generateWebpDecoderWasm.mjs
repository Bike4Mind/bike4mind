// Embeds @jsquash/webp's decoder wasm as base64 so every bundle that moderates images carries it with no
// per-function asset wiring. Re-run after changing the pinned @jsquash/webp version:
//   pnpm --filter @bike4mind/utils generate:webp-wasm
// webpDecoderWasm.test.ts fails while the embedded bytes differ from the installed package's.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { version } = require('@jsquash/webp/package.json');
const wasm = readFileSync(require.resolve('@jsquash/webp/codec/dec/webp_dec.wasm'));
const out = new URL('../src/imageModeration/webpDecoderWasm.generated.ts', import.meta.url);

writeFileSync(
  out,
  `// Generated by scripts/generateWebpDecoderWasm.mjs from @jsquash/webp@${version}. Do not edit.\n` +
    `export const WEBP_DECODER_WASM_VERSION = '${version}';\n\n` +
    `export const WEBP_DECODER_WASM_BASE64 =\n  '${wasm.toString('base64')}';\n`
);
console.log(`wrote ${out.pathname} (${wasm.length} bytes of wasm)`);
