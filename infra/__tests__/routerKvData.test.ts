/** @vitest-environment node */
import { readFileSync } from 'node:fs';
import { afterEach, describe, expect, it, vi } from 'vitest';
import {
  DYNAMIC_RESOURCE_TYPE,
  ROUTER_KV_DATA_NAME_SUFFIXES,
  deleteRouterKvDataWithRouter,
  isRouterKvDataResource,
} from '../routerKvData';

const router = { urn: 'urn:router' };
const transformationArgs = (name: string, type = DYNAMIC_RESOURCE_TYPE, opts: { deletedWith?: unknown } = {}) => ({
  type,
  name,
  props: { store: 'store-arn', namespace: 'ab12' },
  opts: { parent: 'route', ...opts },
});

describe('router KV data teardown', () => {
  it.each([
    'RouterRoute/generated.sst.aws.KvKeys',
    'RouterRoute/generatedRouteKey.sst.aws.KvKeys',
    'RouterRoute/org-filesRoutesUpdate.sst.aws.KvRoutesUpdate',
    'WebKvKeys.sst.aws.KvKeys',
  ])('ties %s to the router so a stage teardown skips its per-key deletes', name => {
    const args = transformationArgs(name);
    expect(deleteRouterKvDataWithRouter(args, router)).toEqual({
      props: args.props,
      opts: { parent: 'route', deletedWith: router },
    });
  });

  it.each([
    ['another dynamic resource', 'WebInvalidation.sst.aws.DistributionInvalidation', DYNAMIC_RESOURCE_TYPE],
    ['the KeyValueStore itself', 'RouterKvStore', 'aws:cloudfront/keyValueStore:KeyValueStore'],
    ['a non-dynamic resource with a matching name', 'x.sst.aws.KvKeys', 'aws:s3/bucket:Bucket'],
  ])('leaves %s unchanged', (_label, name, type) => {
    expect(isRouterKvDataResource(type, name)).toBe(false);
    expect(deleteRouterKvDataWithRouter(transformationArgs(name, type), router)).toBeUndefined();
  });

  it('keeps a deletedWith the resource already names', () => {
    const args = transformationArgs('RouterRoute/x.sst.aws.KvKeys', DYNAMIC_RESOURCE_TYPE, { deletedWith: 'other' });
    expect(deleteRouterKvDataWithRouter(args, router)).toBeUndefined();
  });

  it('matches the resource names and type the pinned SST platform registers', ({ skip }) => {
    const platform = (path: string) => new URL(`../../.sst/platform/${path}`, import.meta.url);
    let kvKeys: string;
    let kvRoutesUpdate: string;
    let dynamicResource: string;
    // The platform is generated by SST and is absent in plain open-core CI checkouts.
    try {
      kvKeys = readFileSync(platform('src/components/aws/providers/kv-keys.ts'), 'utf8');
      kvRoutesUpdate = readFileSync(platform('src/components/aws/providers/kv-routes-update.ts'), 'utf8');
      dynamicResource = readFileSync(platform('node_modules/@pulumi/pulumi/dynamic/index.js'), 'utf8');
    } catch (error) {
      if (error instanceof Error && 'code' in error && error.code === 'ENOENT') {
        skip('SST platform source is not installed');
        return;
      }
      throw error;
    }
    expect(kvKeys).toContain(`\`\${name}${ROUTER_KV_DATA_NAME_SUFFIXES[0]}\``);
    expect(kvRoutesUpdate).toContain(`\`\${name}${ROUTER_KV_DATA_NAME_SUFFIXES[1]}\``);
    // SST passes no module or type, so the dynamic resource type is the default.
    expect(kvKeys).toMatch(/super\(new rpc\.Provider\("Aws\.KvKeys"\), `\$\{name\}[^`]*`, args, opts\)/);
    expect(dynamicResource).toContain('super(`pulumi-nodejs:dynamic${module ? `/${module}` : ""}:${type}`');
    expect(dynamicResource).toMatch(/constructor\(provider, name, props, opts, module, type = "Resource"\)/);
  });
});

describe('router.ts wiring', () => {
  const routerConstructor = vi.fn(function () {
    return { url: { apply: (callback: (value: string) => string) => callback('https://example.test') } };
  });
  Object.assign(routerConstructor, { get: () => ({ url: { apply: () => '' } }) });

  afterEach(() => {
    vi.unstubAllEnvs();
    vi.unstubAllGlobals();
    vi.clearAllMocks();
  });

  async function loadRouter({
    stage,
    dev = false,
    sharedRouter = false,
  }: {
    stage: string;
    dev?: boolean;
    sharedRouter?: boolean;
  }) {
    vi.resetModules();
    vi.doMock('../waf', () => ({ wafWebAcl: undefined }));
    vi.stubEnv('IS_PREVIEW', '');
    vi.stubEnv('DEV_ROUTER_DISTRIBUTION_ID', sharedRouter ? 'shared-router' : '');
    vi.stubEnv('AUTH_NETWORK_ORIGIN_REQUEST_POLICY_ID', 'shared-policy');
    vi.stubEnv('PREVIEW_SHARED_RESPONSE_FUNCTION_ARN', '');
    vi.stubEnv('SERVER_DOMAIN', 'example.test');
    const registerStackTransformation = vi.fn();
    vi.stubGlobal('$app', { stage });
    vi.stubGlobal('$dev', dev);
    vi.stubGlobal('$output', <T>(value: T) => ({ apply: <R>(callback: (resolved: T) => R) => callback(value) }));
    vi.stubGlobal('$transform', vi.fn());
    vi.stubGlobal('$interpolate', (parts: TemplateStringsArray, ...values: unknown[]) =>
      parts.reduce((result, part, index) => result + part + (values[index] ?? ''), '')
    );
    vi.stubGlobal('$util', { runtime: { registerStackTransformation } });
    vi.stubGlobal('aws', { cloudfront: { OriginRequestPolicy: vi.fn(), Function: {} } });
    vi.stubGlobal('random', {
      RandomPassword: class {
        result = 'synthetic-secret';
      },
    });
    vi.stubGlobal('sst', { aws: { Router: routerConstructor, dns: vi.fn() }, Linkable: class {} });
    const module = await import('../router');
    return { registerStackTransformation, router: module.router };
  }

  it('registers the teardown transformation on a preview, bound to its own router', async () => {
    const { registerStackTransformation, router: previewRouter } = await loadRouter({ stage: 'pr123' });
    expect(registerStackTransformation).toHaveBeenCalledTimes(1);
    const [transformation] = registerStackTransformation.mock.calls[0];
    const args = transformationArgs('RouterRoute/generated.sst.aws.KvKeys');
    expect(transformation(args)).toEqual({ props: args.props, opts: { ...args.opts, deletedWith: previewRouter } });
  });

  it.each([
    ['production', { stage: 'production' }],
    ['staging', { stage: 'dev' }],
    ['a personal sst dev stage on the shared router', { stage: 'pr123', dev: true, sharedRouter: true }],
  ])('leaves %s unchanged', async (_label, options) => {
    const { registerStackTransformation } = await loadRouter(options);
    expect(registerStackTransformation).not.toHaveBeenCalled();
  });
});
