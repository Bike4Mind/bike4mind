/** @vitest-environment node */
import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
import ts from 'typescript';
import { describe, expect, it, vi } from 'vitest';
import { minifyRouterFunction, pinUrlOriginHost, prepareRouterRequestFunction } from '../routerFunctionCode';

const helpers = `
function setForwardedHost() {
  event.request.headers['x-forwarded-host'] = event.request.headers.host;
}
function setUrlOrigin(urlHost, override) {
  setForwardedHost();
  const origin = {
    domainName: urlHost,
    customOriginConfig: { protocol: 'https' },
    originAccessControlConfig: { enabled: false }
  };
  override = override || {};
  if (override.protocol === 'http') delete origin.customOriginConfig;
  cf.updateRequestOrigin(origin);
}
function setS3Origin(s3Domain) {
  cf.updateRequestOrigin({ domainName: s3Domain, originAccessControlConfig: { enabled: true } });
}`;

describe('router origin Host forwarding', () => {
  it.each([{}, { protocol: 'http' }])('pins the backend Host while keeping the viewer hostname: %j', override => {
    const updateRequestOrigin = vi.fn();
    const event = { request: { headers: { host: { value: 'app.example.test' } } } };
    runInNewContext(`${prepareRouterRequestFunction(helpers)}; setUrlOrigin('backend.example.test', override);`, {
      event,
      override,
      cf: { updateRequestOrigin },
    });
    expect(updateRequestOrigin).toHaveBeenCalledWith(
      expect.objectContaining({ domainName: 'backend.example.test', hostHeader: 'backend.example.test' })
    );
    expect(event.request.headers).toEqual({
      host: { value: 'app.example.test' },
      'x-forwarded-host': { value: 'app.example.test' },
    });
  });

  it('leaves S3 origin selection unchanged', () => {
    const updateRequestOrigin = vi.fn();
    runInNewContext(`${prepareRouterRequestFunction(helpers)}; setS3Origin('bucket.example.test');`, {
      cf: { updateRequestOrigin },
    });
    expect(updateRequestOrigin).toHaveBeenCalledWith({
      domainName: 'bucket.example.test',
      originAccessControlConfig: { enabled: true },
    });
  });

  it.each(['', helpers.replace('domainName: urlHost', 'domainName: otherHost'), helpers + helpers])(
    'rejects missing, changed or ambiguous SST helper shapes',
    code => {
      expect(() => pinUrlOriginHost(code)).toThrow('SST URL origin helper changed');
    }
  );

  it('supports the pinned SST lazy-router helper when the platform is installed', ({ skip }) => {
    const platform = new URL('../../.sst/platform/src/components/aws/router.ts', import.meta.url);
    // The platform is generated by SST and is absent in plain open-core CI checkouts.
    let source: string;
    try {
      source = readFileSync(platform, 'utf8');
    } catch (error) {
      if (error instanceof Error && 'code' in error && error.code === 'ENOENT') {
        skip('SST platform source is not installed');
        return;
      }
      throw error;
    }
    const parsed = ts.createSourceFile('router.ts', source, ts.ScriptTarget.Latest, true);
    const matches: string[] = [];
    const visit = (node: ts.Node) => {
      if (ts.isVariableDeclaration(node) && node.name.getText(parsed) === 'CF_ROUTER_INJECTION') {
        if (node.initializer && ts.isTaggedTemplateExpression(node.initializer)) {
          const template = node.initializer.template;
          matches.push(
            ts.isNoSubstitutionTemplateLiteral(template)
              ? template.text
              : template.head.text + template.templateSpans.map(span => '0' + span.literal.text).join('')
          );
        }
      }
      ts.forEachChild(node, visit);
    };
    visit(parsed);
    expect(matches).toHaveLength(1);
    expect(prepareRouterRequestFunction(matches[0])).toContain('hostHeader:urlHost');
    expect(prepareRouterRequestFunction(minifyRouterFunction(matches[0]))).toContain('hostHeader:urlHost');
  });
});
