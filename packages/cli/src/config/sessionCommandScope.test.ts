import { describe, it, expect } from 'vitest';
import { sessionCommandPrefixes } from './sessionCommandScope.js';

describe('sessionCommandPrefixes', () => {
  it.each([
    ['git status', ['git status']],
    ['git status -s', ['git status']],
    ['git log --oneline -5', ['git log']],
    ['git grep -n todo', ['git grep']],
    ['git branch', ['git branch']],
    ['git branch -a -vv', ['git branch']],
    ['git stash list', ['git stash list']],
    ['ls -la src', ['ls']],
    ['git status && git log --oneline', ['git status', 'git log']],
    ['git log | head -5', ['git log', 'head']],
    ['(ls packages); pwd', ['ls', 'pwd']],
    ['git log 2>&1 | grep fix', ['git log', 'grep']],
    ['sort -u names.txt', ['sort']],
    ['npm test', ['npm test']],
    ['npm test -- --watch=false', ['npm test']],
    ['npm run lint', ['npm run lint']],
    ['pnpm typecheck', ['pnpm typecheck']],
    ['yarn format:check', ['yarn format:check']],
    ['pnpm test > /dev/null', ['pnpm test']],
    ['vitest run src', ['vitest']],
    ['go test ./...', ['go test']],
    ['cargo clippy', ['cargo clippy']],
    ['ls *.ts', ['ls']],
    ['git status\n', ['git status']],
  ])('scopes %j to %j', (command, expected) => {
    expect(sessionCommandPrefixes(command)).toEqual(expected);
  });

  it.each([
    ['empty', ''],
    ['a program off the allow-list', 'sed -n 1p file'],
    ['cp', 'cp a b'],
    ['find', 'find . -name x'],
    ['awk', 'awk 1 file'],
    ['a program name in another case', 'Git status'],
    ['npm create', 'npm create vite'],
    ['npm run with an unlisted script', 'npm run x'],
    ['a bare unlisted script', 'pnpm dev'],
    ['git rebase', 'git rebase -x true main'],
    ['git bisect', 'git bisect run true'],
    ['git difftool', 'git difftool'],
    ['git grep -O', 'git grep -O todo'],
    ['git branch with a name', 'git branch topic'],
    ['git stash without list', 'git stash'],
    ['git push', 'git push origin main'],
    ['git -c option is not remembered', 'git -c core.pager=less log'],
    ['git -C before the subcommand', 'git -C repo status'],
    ['git --ext-diff', 'git diff --ext-diff'],
    ['git --textconv', 'git log -p --textconv'],
    ['git --output', 'git diff --output=x.patch'],
    ['npm --prefix', 'npm test --prefix ../other'],
    ['cargo --config', 'cargo --config x build'],
    ['cargo run', 'cargo run'],
    ['go run', 'go run .'],
    ['go test -exec', 'go test -exec x ./...'],
    ['sort -o', 'sort -uo out.txt in.txt'],
    ['rg --pre', 'rg --pre x pattern'],
    ['uniq with an output file', 'uniq in.txt out.txt'],
    ['command substitution', 'git log $(ls)'],
    ['backticks', 'git log `ls`'],
    ['process substitution', 'diff <(ls a) <(ls b)'],
    ['an embedded newline', 'git status\nls'],
    ['an env assignment', 'GIT_DIR=/tmp git log'],
    ['a write redirect', 'git log > ~/.profile'],
    ['a herestring', 'cat <<< hi'],
    ['a variable as the program', '$EDITOR notes.txt'],
    ['a relative program path', './script.sh'],
    ['a nested program path', 'bin/ls'],
    ['an interpreter word', 'ls | xargs sh'],
    ['a for loop', 'for f in *; do wc -l $f; done'],
    ['an if block', 'if true; then ls; fi'],
    ['a while loop', 'while true; do ls; done'],
    ['a brace group', '{ ls; }'],
    ['a test expression', '[[ -f x ]] && ls'],
    ['a negated command', '! ls'],
    ['a network program', 'curl https://example.com'],
    ['a network program later in a chain', 'git status && curl https://example.com'],
    ['a network program after ;', 'git status; nc example.com 80'],
    ['a high-risk command', 'rm -rf /'],
  ])('refuses %s', (_label, command) => {
    expect(sessionCommandPrefixes(command)).toBeNull();
  });
});
