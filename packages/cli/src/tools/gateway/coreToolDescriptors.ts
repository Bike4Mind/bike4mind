import type { ToolDescriptor, ToolSource } from './toolDescriptor.js';

const CORE: ToolSource = { kind: 'core' };
const CLI: ToolSource = { kind: 'cli' };

const pureCompute = (): ToolDescriptor => ({ source: CORE, effect: 'none', approval: 'auto_approve' });

// The agent's own bookkeeping and delegation. These ran unwrapped before every tool went
// through the permission wrapper; they stay prompt-free there. A delegated subagent runs its
// own tools through the wrapper under its mode ceiling. Not all are side-effect free
// (work_item_* write server state, cancel_background_agent stops a run), so plan mode lets
// them through as read-only.
const sessionTool = (): ToolDescriptor => ({ source: CLI, effect: 'session', approval: 'auto_approve' });

const reader = (source: ToolSource = CORE, extra: Partial<ToolDescriptor> = {}): ToolDescriptor => ({
  source,
  effect: 'read',
  approval: 'prompt_default',
  ...extra,
});

const fileWriter = (): ToolDescriptor => ({
  source: CORE,
  effect: 'write',
  approval: 'prompt_always',
  writePathArg: 'path',
});

// The CLI wires no latticeModels DB adapter, so the Lattice tools only build and return model
// JSON in memory: pure compute here, still prompting by default as they always have.
const lattice = (): ToolDescriptor => ({ source: CORE, effect: 'none', approval: 'prompt_default' });

