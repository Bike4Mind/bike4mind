import type { DesignTokens } from '../../schema';
import type { TokenEmitter } from '../types';
import { resolveNativeTheme, type NamedValue, type NativeColorRole, type NativeTheme, type Rgba } from './nativeTheme';
import type { EmittedFiles } from './types';

// Emits the native theme as a Kotlin/Compose source file. Unlike the Swift
// emitter, the file is self-contained: BrandColorPair is declared here, so the
// output compiles without any hand-written companion file.

export const KOTLIN_TOKENS_FILE = 'BrandTokens.kt';
export const KOTLIN_PACKAGE = 'com.bike4mind.app.ui';

const HEADER = ['// Generated by @bike4mind/design-tokens (src/emitters/native/kotlin.ts). Do not edit by hand.'];

const hexByte = (value: number): string => value.toString(16).toUpperCase().padStart(2, '0');

/** ARGB literal for Compose's Color(Long). Alpha is rounded to a byte. */
const argb = (color: Rgba): string => {
  const alpha = Math.round(color.alpha * 255);
  return `0x${hexByte(alpha)}${hexByte(color.red)}${hexByte(color.green)}${hexByte(color.blue)}`;
};

const colorValue = (color: Rgba): string => `Color(${argb(color)})`;

const kotlinNumber = (value: number): string => String(value);

/** Integer values read as `8.dp`; fractional ones need the float suffix (`1.5f`). */
const dpValue = (value: number): string =>
  Number.isInteger(value) ? `${kotlinNumber(value)}.dp` : `${kotlinNumber(value)}f.dp`;

const spValue = (value: number): string =>
  Number.isInteger(value) ? `${kotlinNumber(value)}.sp` : `${kotlinNumber(value)}f.sp`;

const floatValue = (value: number): string => `${kotlinNumber(value)}f`;

const colorLines = (role: NativeColorRole): string[] => [
  `        /** ${role.description} */`,
  `        val ${role.name} = BrandColorPair(`,
  `            light = ${colorValue(role.light)},`,
  `            dark = ${colorValue(role.dark)},`,
  '        )',
];

const valueObject = (
  name: string,
  doc: string,
  values: readonly NamedValue[],
  indent: string,
  format: (value: number) => string,
  type?: string
): string[] => [
  `${indent}/** ${doc} */`,
  `${indent}object ${name} {`,
  ...values.map(entry => `${indent}    val ${entry.name}${type ? `: ${type}` : ''} = ${format(entry.value)}`),
  `${indent}}`,
];

export const emitKotlinTokens = (theme: NativeTheme): string =>
  [
    ...HEADER,
    `package ${KOTLIN_PACKAGE}`,
    '',
    'import androidx.compose.ui.graphics.Color',
    'import androidx.compose.ui.unit.dp',
    'import androidx.compose.ui.unit.sp',
    '',
    '/** A color role with a light and a dark value. */',
    'data class BrandColorPair(val light: Color, val dark: Color)',
    '',
    '/** The Bike4Mind design tokens, resolved from packages/design-tokens (the web theme source). */',
    'object BrandTokens {',
    '    /** Color roles, each a light/dark pair. */',
    '    object Colors {',
    ...theme.colors.flatMap((role, index) => [...(index === 0 ? [] : ['']), ...colorLines(role)]),
    '    }',
    '',
    ...valueObject('Spacing', 'Spacing steps in dp (multiples of the 8dp web unit).', theme.spacing, '    ', dpValue),
    '',
    ...valueObject('Radius', 'Corner radii in dp (the web radius scale).', theme.radii, '    ', dpValue),
    '',
    '    /** Type ramp. Sizes are sp at the default font scale (1rem = 16sp). */',
    '    object Typography {',
    `        const val familyName = "${theme.typography.familyName}"`,
    '',
    ...valueObject('Size', 'Font sizes in sp.', theme.typography.sizes, '        ', spValue),
    '',
    ...valueObject('Weight', 'CSS font weights (100-1000).', theme.typography.weights, '        ', kotlinNumber, 'Int'),
    '',
    ...valueObject(
      'LineHeight',
      'Line heights as multiples of the font size.',
      theme.typography.lineHeights,
      '        ',
      floatValue,
      'Float'
    ),
    '    }',
    '}',
    '',
  ].join('\n');

export const emitKotlin = (tokens: DesignTokens): EmittedFiles => {
  const theme = resolveNativeTheme(tokens);
  return {
    [KOTLIN_TOKENS_FILE]: emitKotlinTokens(theme),
  };
};

export const kotlinEmitter: TokenEmitter<EmittedFiles> = {
  target: 'kotlin',
  emit: emitKotlin,
};
