import type { DesignTokens } from '../../schema';
import type { TokenEmitter } from '../types';
import { resolveNativeTheme, type NamedValue, type NativeColorRole, type NativeTheme, type Rgba } from './nativeTheme';
import type { EmittedFiles } from './types';

// Emits the native theme as Swift source plus the asset-catalog AccentColor.
// The Swift file only carries data; the types it builds (BrandRGBA,
// BrandColorPair) are hand-written in B4MKit's Theme/BrandTheme.swift.

export const SWIFT_TOKENS_FILE = 'BrandTokens.swift';
export const SWIFT_ACCENT_COLOR_FILE = 'AccentColor.colorset/Contents.json';

const HEADER = [
  '// Generated by @bike4mind/design-tokens (src/emitters/native/swift.ts). Do not edit by hand:',
  '// change the tokens, then run `make generate-tokens` in apps/ios.',
];

const hexByte = (value: number): string => value.toString(16).toUpperCase().padStart(2, '0');

const hexRgb = (color: Rgba): string => `0x${hexByte(color.red)}${hexByte(color.green)}${hexByte(color.blue)}`;

const swiftNumber = (value: number): string => String(value);

const swiftRgba = (color: Rgba): string =>
  color.alpha === 1 ? `BrandRGBA(${hexRgb(color)})` : `BrandRGBA(${hexRgb(color)}, alpha: ${swiftNumber(color.alpha)})`;

const colorLines = (role: NativeColorRole): string[] => [
  `    /// ${role.description}`,
  `    public static let ${role.name} = BrandColorPair(`,
  `      light: ${swiftRgba(role.light)}, dark: ${swiftRgba(role.dark)})`,
];

const valueEnum = (
  name: string,
  doc: string,
  type: string,
  values: readonly NamedValue[],
  indent: string
): string[] => [
  `${indent}/// ${doc}`,
  `${indent}public enum ${name} {`,
  ...values.map(entry => `${indent}  public static let ${entry.name}: ${type} = ${swiftNumber(entry.value)}`),
  `${indent}}`,
];

export const emitSwiftTokens = (theme: NativeTheme): string =>
  [
    ...HEADER,
    '',
    'import CoreGraphics',
    '',
    '/// The Bike4Mind design tokens, resolved from packages/design-tokens (the web theme source).',
    'public enum BrandTokens {',
    '  /// Color roles, each a light/dark pair.',
    '  public enum Colors {',
    ...theme.colors.flatMap((role, index) => [...(index === 0 ? [] : ['']), ...colorLines(role)]),
    '  }',
    '',
    ...valueEnum('Spacing', 'Spacing steps in points (multiples of the 8pt web unit).', 'CGFloat', theme.spacing, '  '),
    '',
    ...valueEnum('Radius', 'Corner radii in points (the web radius scale).', 'CGFloat', theme.radii, '  '),
    '',
    '  /// Type ramp. Sizes are points at the default Dynamic Type size (1rem = 16pt).',
    '  public enum Typography {',
    `    public static let familyName = "${theme.typography.familyName}"`,
    '',
    ...valueEnum('Size', 'Font sizes in points.', 'CGFloat', theme.typography.sizes, '    '),
    '',
    ...valueEnum('Weight', 'CSS font weights (100-1000).', 'Int', theme.typography.weights, '    '),
    '',
    ...valueEnum(
      'LineHeight',
      'Line heights as multiples of the font size.',
      'CGFloat',
      theme.typography.lineHeights,
      '    '
    ),
    '  }',
    '}',
    '',
  ].join('\n');

const assetComponents = (color: Rgba): string =>
  `{ "alpha" : "${color.alpha.toFixed(3)}", "blue" : "0x${hexByte(color.blue)}", ` +
  `"green" : "0x${hexByte(color.green)}", "red" : "0x${hexByte(color.red)}" }`;

/** The Xcode asset-catalog color set, in the layout Xcode itself writes. */
export const emitAccentColorSet = (role: NativeColorRole): string =>
  [
    '{',
    '  "colors" : [',
    '    {',
    `      "color" : { "color-space" : "srgb", "components" : ${assetComponents(role.light)} },`,
    '      "idiom" : "universal"',
    '    },',
    '    {',
    '      "appearances" : [ { "appearance" : "luminosity", "value" : "dark" } ],',
    `      "color" : { "color-space" : "srgb", "components" : ${assetComponents(role.dark)} },`,
    '      "idiom" : "universal"',
    '    }',
    '  ],',
    '  "info" : { "author" : "xcode", "version" : 1 }',
    '}',
    '',
  ].join('\n');

export const emitSwift = (tokens: DesignTokens): EmittedFiles => {
  const theme = resolveNativeTheme(tokens);
  return {
    [SWIFT_TOKENS_FILE]: emitSwiftTokens(theme),
    [SWIFT_ACCENT_COLOR_FILE]: emitAccentColorSet(theme.accentRole),
  };
};

export const swiftEmitter: TokenEmitter<EmittedFiles> = {
  target: 'swift',
  emit: emitSwift,
};
